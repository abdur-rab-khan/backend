-- "ABS(-10)": It returns the absolute value of -10, which is 10.
SELECT ABS(-10) AS absolute_value;

-- "DIV(4, 2)": It performs integer division of 4 by 2, resulting in 2.
SELECT DIV(4, 2) AS integer_division;

-- "FLOOR(4.7)": It rounds down the number 4.7 to the nearest integer, which is 4.
SELECT FLOOR(4.7) AS floored_value;

-- "ROUND(4.567, 2)": It rounds the number 4.567 to 2 decimal places, resulting in 4.57.
SELECT ROUND(4.567, 2) AS rounded_value;

-- "CEIL(4.2)": It rounds up the number 4.2 to the nearest integer, which is 5.
SELECT CEIL(4.2) AS ceiled_value;

